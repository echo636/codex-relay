"""Two-browser command interactions, backed exclusively by fake_codex.py."""
from playwright.sync_api import expect


def check_commands(page, phone, harness, out):
    tid = phone.evaluate('state.current')
    initial_turns = len(harness.gateway.history(tid)['turns'])

    def command(tab, text):
        expect(tab.locator('dialog[open]')).to_have_count(0)
        tab.locator('#prompt').fill(text)
        tab.locator('#send').click()

    command(phone, '/permission')
    expect(phone.locator('#permission-dialog')).to_be_visible()
    expect(phone.locator('#permission-current')).to_contain_text('workspaceWrite')
    command(page, '/permissions full')
    expect(phone.locator('#permission-current')).to_have_text('Full Access · 完全访问')
    expect(page.locator('#notice')).to_contain_text('已启用 Full Access')
    phone.locator('#permission-dialog .dialog-close').click()
    command(phone, '/permissions')
    expect(phone.locator('#permission-current')).to_have_text('Full Access · 完全访问')
    phone.locator('#permission-full').click()
    expect(phone.locator('#notice')).to_contain_text('已启用 Full Access')
    phone.locator('#permission-dialog .dialog-close').click()
    assert len(harness.gateway.history(tid)['turns']) == initial_turns

    # Keyboard filtering/autocomplete and phone tap selection open the real UI.
    phone.locator('#prompt').fill('/go')
    expect(phone.locator('#slash-menu')).to_be_visible()
    phone.locator('#prompt').press('Tab')
    expect(phone.locator('#prompt')).to_have_value('/goal')
    phone.locator('#prompt').press('Enter')
    expect(phone.locator('#goal-dialog')).to_be_visible()
    expect(phone.locator('#prompt')).to_have_value('')
    phone.locator('#goal-objective').fill('验证命令同步 <img onerror=alert(1)>')
    phone.locator('#goal-budget').fill('50000')
    phone.locator('#goal-save').click()
    expect(phone.locator('#goal-dialog')).not_to_be_visible()
    for tab in (phone, page):
        expect(tab.locator('#goal-panel')).to_be_visible()
        expect(tab.locator('#goal-status')).to_have_text('目标进行中')
        expect(tab.locator('#goal-objective-preview')).to_have_text('验证命令同步 <img onerror=alert(1)>')
        expect(tab.locator('#goal-panel img')).to_have_count(0)
        expect(tab.locator('#goal-usage')).to_contain_text('50,000')
    assert len(harness.gateway.history(tid)['turns']) == initial_turns

    # Native progress updates are reflected on both clients, not local fake state.
    harness.gateway.rpc.call('fixture/goal/progress', {'threadId': tid, 'progress': {'tokensUsed': 1234, 'timeUsedSeconds': 125}})
    for tab in (phone, page): expect(tab.locator('#goal-usage')).to_contain_text('1,234 / 50,000 tokens · 2 分 5 秒')
    phone.screenshot(path=str(out/'slash-goal-mobile.png'))
    page.screenshot(path=str(out/'slash-goal-desktop.png'))
    command(phone, '/goal pause')
    for tab in (phone, page): expect(tab.locator('#goal-status')).to_have_text('目标已暂停')
    page.locator('#goal-toggle').click()
    for tab in (phone, page): expect(tab.locator('#goal-status')).to_have_text('目标进行中')
    phone.reload()
    expect(phone.locator('#goal-usage')).to_contain_text('1,234 / 50,000')
    command(phone, '/goal edit')
    expect(phone.locator('#goal-objective')).to_have_value('验证命令同步 <img onerror=alert(1)>')
    phone.locator('#goal-objective').fill('编辑后的目标')
    phone.locator('#goal-save').click()
    for tab in (phone, page): expect(tab.locator('#goal-objective-preview')).to_have_text('编辑后的目标')

    # A stale editor cannot overwrite a newer goal from another device.
    command(phone, '/goal edit')
    command(page, '/goal 电脑端的新目标')
    expect(phone.locator('#goal-objective-preview')).to_have_text('电脑端的新目标')
    phone.locator('#goal-objective').fill('旧编辑器')
    phone.locator('#goal-save').click()
    expect(phone.locator('#goal-error')).to_contain_text('目标已在其他设备更新')
    phone.locator('#goal-dialog .dialog-close').click()
    expect(phone.locator('#goal-objective-preview')).to_have_text('电脑端的新目标')
    command(phone, '/status')
    expect(phone.locator('#command-status')).to_be_visible()
    expect(phone.locator('#command-status-content')).to_contain_text(tid)
    expect(phone.locator('#command-status-content')).to_contain_text('电脑端的新目标')
    phone.locator('#command-status .dialog-close').click()
    command(phone, '/model')
    expect(phone.locator('#model-dialog')).to_be_visible()
    phone.locator('#model-dialog .dialog-close').click()
    command(phone, '/not-supported')
    expect(phone.locator('#notice')).to_contain_text('网页暂不支持')
    expect(phone.locator('#prompt')).to_have_value('/not-supported')
    assert len(harness.gateway.history(tid)['turns']) == initial_turns

    # Commands do not wait behind a running turn or go into the next-turn queue.
    command(phone, 'hang')
    expect(phone.locator('#stop')).to_be_visible()
    command(phone, '/permission full')
    expect(phone.locator('#notice')).to_contain_text('从下一轮开始生效')
    expect(phone.locator('#stop')).to_be_visible()
    phone.locator('#message-mode').select_option('send')
    command(phone, '/goal pause')
    expect(phone.locator('#goal-status')).to_have_text('目标已暂停')
    expect(phone.locator('#stop')).to_be_visible()
    command(phone, '/compact')
    expect(phone.locator('#notice')).to_contain_text('等待当前任务结束')
    phone.locator('#message-mode').select_option('queue')
    command(phone, '/goal resume')
    expect(phone.locator('#goal-status')).to_have_text('目标进行中')
    expect(phone.locator('#queue-list .queue-row')).to_have_count(0)
    command(phone, '/stop')
    expect(phone.locator('#stop')).to_be_hidden()
    phone.locator('#message-mode').select_option('auto')
    command(phone, '/compact')
    expect(phone.locator('#messages')).to_contain_text('会话上下文已整理')
    command(phone, '/goal clear')
    for tab in (phone, page): expect(tab.locator('#goal-panel')).to_be_hidden()
    command(phone, '//goal 这条是普通文字')
    expect(phone.locator('#messages')).to_contain_text('/goal 这条是普通文字')
    expect(phone.locator('#stop')).to_be_hidden()
    assert harness.gateway.get_goal(tid)['goal'] is None

    # Full menus and goal controls remain contained at narrow phone widths.
    command(phone, '/goal 窄屏目标显示')
    for width in (320, 360, 390):
        phone.set_viewport_size({'width': width, 'height': 844})
        phone.locator('#prompt').fill('/')
        expect(phone.locator('#slash-menu')).to_be_visible()
        assert phone.evaluate('document.documentElement.scrollWidth <= innerWidth')
        assert phone.locator('#composer').evaluate('(n) => n.scrollWidth <= n.clientWidth')
        phone.locator('#prompt').press('Escape')
        expect(phone.locator('#slash-menu')).to_be_hidden()
    phone.set_viewport_size({'width': 390, 'height': 844})
    phone.locator('#prompt').fill('/goal')
    phone.screenshot(path=str(out/'slash-menu-mobile.png'))
    command(phone, '/help')
    expect(phone.locator('#command-help')).to_be_visible()
    expect(phone.locator('#command-help-list')).to_contain_text('/goal pause')
    phone.locator('#command-help .dialog-close').click()
    command(phone, '/goal clear')
    expect(phone.locator('#goal-panel')).to_be_hidden()
    expect(phone.locator('#prompt')).to_have_value('')
